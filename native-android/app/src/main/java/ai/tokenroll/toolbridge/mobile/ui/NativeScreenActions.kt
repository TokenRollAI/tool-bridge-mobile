package ai.tokenroll.toolbridge.mobile

import android.graphics.Bitmap
import android.os.CancellationSignal
import org.json.JSONObject

/** Read an immutable, in-memory presentation snapshot. Runtime owns storage, policy and I/O. */
interface NativeScreenActions {
    fun snapshot(): JSONObject
    /** Unfiltered lookup so opening the last unread item keeps its article visible. */
    fun message(messageId: String): JSONObject?
    fun perform(action: NativeScreenAction, complete: (success: Boolean) -> Unit)
    fun openRemoteControlConfiguration()
    /** Host enforces source, redirect, byte and pixel limits before returning the preview. */
    fun resolveInboxImage(url: String, cancellation: CancellationSignal, complete: (Bitmap?) -> Unit)
}

sealed class NativeScreenAction {
    class InboxView(val searchQuery: String, val sort: String, val unreadOnly: Boolean) : NativeScreenAction()
    class MarkRead(val messageId: String) : NativeScreenAction()
    object MarkAllRead : NativeScreenAction()
    object ClearInbox : NativeScreenAction()
    object ClearActivity : NativeScreenAction()
    // Keep the key out of autogenerated toString, UI state bundles and feedback.
    class SaveConnection(val origin: String, val apiKey: String, val deviceId: String?) : NativeScreenAction()
    object ClearConnection : NativeScreenAction()
    class SetControlMode(val mode: String) : NativeScreenAction()
    class SetBackground(val enabled: Boolean) : NativeScreenAction()
    enum class Permission { CAMERA, NOTIFICATIONS }
    class PermissionAction(val permission: Permission, val openSettings: Boolean) : NativeScreenAction()
    class CancelTimer(val timerId: String) : NativeScreenAction()
    object StopAttention : NativeScreenAction()
    enum class Playback { PAUSE, RESUME, STOP }
    class ControlMedia(val sessionId: String, val playback: Playback) : NativeScreenAction()
    class OpenInboxLink(val url: String) : NativeScreenAction()
}
